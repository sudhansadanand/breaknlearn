#!/usr/bin/env node
// Generates supabase/seed/0001_curriculum.sql from docs/handoff/reference/curriculum_seed_prototype.json.
// Deterministic: same input -> byte-identical output. Run: node scripts/db/gen-curriculum-seed.mjs [--check]
// Topics are an EDITORIAL outline (spec §0): every node is authority='editorial_unverified', review_status='draft'.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const SRC = join(ROOT, "docs", "handoff", "reference", "curriculum_seed_prototype.json");
const OUT = join(ROOT, "supabase", "seed", "0001_curriculum.sql");
const MULTIPLICATION_PROTOTYPE_ID = "grade2-math-multiplication";
const MULTIPLICATION_TOPIC_KEY = "grade2.math.multiplication";

const proto = JSON.parse(readFileSync(SRC, "utf8"));
const q = (s) => (s === null || s === undefined ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const subjectKey = (label) => label.toLowerCase().replace(/ & /g, "_").replace(/[^a-z0-9]+/g, "_");
const slug = (s) => s.toLowerCase().replace(/&/g, " and ").replace(/[^a-z0-9]+/g, "_").replace(/^_+|_+$/g, "");

const seen = new Set();
const perSubject = new Map();
const rows = proto.topics.map((t) => {
  const subject = subjectKey(t.subject);
  const key = t.id === MULTIPLICATION_PROTOTYPE_ID ? MULTIPLICATION_TOPIC_KEY : `grade${t.grade}.${subject}.${slug(t.topic)}`;
  if (seen.has(key)) throw new Error(`duplicate topic key ${key}`);
  seen.add(key);
  const groupKey = `${t.grade}.${subject}`;
  const sort = (perSubject.get(groupKey) ?? 0) + 1;
  perSubject.set(groupKey, sort);
  const isCisce = t.board === "CISCE";
  const provenance = {
    prototype_id: t.id,
    board: t.board,
    alignment: t.alignment,
    source: t.source,
    origin: isCisce ? "proposed_from_cisce" : t.alignment === "provisional" ? "proposed_enrichment" : "existing_live_lessons",
  };
  return { key, grade: t.grade, subject, title: t.topic, sort, framework: isCisce ? (t.grade === 2 ? "primary" : "upper") : null, provenance };
});
if (rows.length !== 80) throw new Error(`expected 80 topics, got ${rows.length}`);

const values = rows
  .map((r) => `  (${q(r.key)}, ${r.grade}, ${q(r.subject)}, ${q(r.title)}, ${r.sort}, ${q(r.framework)}, ${q(JSON.stringify(r.provenance))}::jsonb)`)
  .join(",\n");

const sql = `-- GENERATED by scripts/db/gen-curriculum-seed.mjs from docs/handoff/reference/curriculum_seed_prototype.json.
-- Do not edit by hand. Core seed (all environments): frameworks, subject nodes, the 80 editorial topics.
-- The topic labels are preliminary editorial mappings, NOT verified CISCE standards (spec §0, M02):
-- every node is authority='editorial_unverified' (enrichment subjects: 'local_enrichment'), review_status='draft'.

insert into bnl.source_documents (id, source_type, url, title, version_label)
values
  (bnl.uuid_v5('6f1d2a0e-6b1e-4a35-9a4e-2f6c3b8d9e10', 'source.cisce.primary.2016'), 'official_pdf',
   ${q(proto.provenance.primary)}, 'CISCE Primary Curriculum', '2016'),
  (bnl.uuid_v5('6f1d2a0e-6b1e-4a35-9a4e-2f6c3b8d9e10', 'source.cisce.upper_primary.2016'), 'official_pdf',
   ${q(proto.provenance.upperPrimary)}, 'CISCE Upper Primary Curriculum', '2016')
on conflict (id) do nothing;

insert into bnl.curriculum_frameworks (id, board, level, version_label, source_document_id)
values
  (bnl.uuid_v5('6f1d2a0e-6b1e-4a35-9a4e-2f6c3b8d9e10', 'framework.cisce.primary.2016'), 'CISCE', 'primary', '2016',
   bnl.uuid_v5('6f1d2a0e-6b1e-4a35-9a4e-2f6c3b8d9e10', 'source.cisce.primary.2016')),
  (bnl.uuid_v5('6f1d2a0e-6b1e-4a35-9a4e-2f6c3b8d9e10', 'framework.cisce.upper_primary.2016'), 'CISCE', 'upper_primary', '2016',
   bnl.uuid_v5('6f1d2a0e-6b1e-4a35-9a4e-2f6c3b8d9e10', 'source.cisce.upper_primary.2016'))
on conflict (id) do nothing;

-- Subject nodes for every grade subject (GRADE_SUBJECTS order). CISCE subjects stay editorial_unverified
-- until a reviewer cites the source; enrichment subjects are local_enrichment, never CISCE.
insert into bnl.curriculum_nodes (id, framework_id, stable_key, parent_id, grade, subject_key, node_type, title,
  authority, review_status, provenance, sort_order)
select bnl.uuid_v5('6f1d2a0e-6b1e-4a35-9a4e-2f6c3b8d9e10', 'grade' || gs.grade || '.' || gs.subject_key),
       case when gs.authority = 'cisce' then bnl.uuid_v5('6f1d2a0e-6b1e-4a35-9a4e-2f6c3b8d9e10',
         case when gs.grade = 2 then 'framework.cisce.primary.2016' else 'framework.cisce.upper_primary.2016' end) end,
       'grade' || gs.grade || '.' || gs.subject_key, null, gs.grade, gs.subject_key, 'subject', gs.label,
       case when gs.authority = 'cisce' then 'editorial_unverified' else 'local_enrichment' end, 'draft',
       jsonb_build_object('subject_authority', gs.authority, 'icon', gs.icon), gs.sort_order
from bnl.grade_subjects gs
on conflict (stable_key) do nothing;

insert into bnl.curriculum_nodes (id, framework_id, stable_key, parent_id, grade, subject_key, node_type, title,
  authority, review_status, provenance, sort_order)
select bnl.uuid_v5('6f1d2a0e-6b1e-4a35-9a4e-2f6c3b8d9e10', t.stable_key),
       case t.framework
         when 'primary' then bnl.uuid_v5('6f1d2a0e-6b1e-4a35-9a4e-2f6c3b8d9e10', 'framework.cisce.primary.2016')
         when 'upper' then bnl.uuid_v5('6f1d2a0e-6b1e-4a35-9a4e-2f6c3b8d9e10', 'framework.cisce.upper_primary.2016')
       end,
       t.stable_key,
       bnl.uuid_v5('6f1d2a0e-6b1e-4a35-9a4e-2f6c3b8d9e10', 'grade' || t.grade || '.' || t.subject_key),
       t.grade, t.subject_key, 'topic', t.title, 'editorial_unverified', 'draft', t.provenance, t.sort_order
from (values
${values}
) as t(stable_key, grade, subject_key, title, sort_order, framework, provenance)
on conflict (stable_key) do nothing;

insert into bnl.learning_outcomes (id, curriculum_node_id, stable_key, statement, authority, review_status)
values (bnl.uuid_v5('6f1d2a0e-6b1e-4a35-9a4e-2f6c3b8d9e10', 'outcome.${MULTIPLICATION_TOPIC_KEY}'),
        bnl.uuid_v5('6f1d2a0e-6b1e-4a35-9a4e-2f6c3b8d9e10', '${MULTIPLICATION_TOPIC_KEY}'),
        '${MULTIPLICATION_TOPIC_KEY}',
        'Understands multiplication as equal groups and recalls the 1 to 10 times tables (editorial wording, unverified).',
        'editorial_unverified', 'draft')
on conflict (stable_key) do nothing;

do $check$
begin
  if (select count(*) from bnl.curriculum_nodes where node_type = 'topic') < 80 then
    raise exception 'curriculum seed: expected 80 topic nodes';
  end if;
  if not exists (select 1 from bnl.curriculum_nodes
                 where id = '58be84d6-b23e-5332-80a7-f7460dd3933f' and stable_key = '${MULTIPLICATION_TOPIC_KEY}') then
    raise exception 'curriculum seed: MULTIPLICATION_TOPIC_ID mismatch with @bnl/contracts';
  end if;
end
$check$;
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(OUT, "utf8");
  if (current !== sql) {
    console.error("supabase/seed/0001_curriculum.sql is out of date; run node scripts/db/gen-curriculum-seed.mjs");
    process.exit(1);
  }
  console.log("curriculum seed up to date");
} else {
  writeFileSync(OUT, sql);
  console.log(`wrote ${OUT} (${rows.length} topics)`);
}
